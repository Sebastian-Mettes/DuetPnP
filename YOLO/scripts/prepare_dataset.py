#!/usr/bin/env python3
"""
Prepare YOLO-OBB dataset by splitting into train/val sets.

Creates:
- data/train/images/
- data/train/labels/
- data/val/images/
- data/val/labels/
- config/dataset.yaml

Usage:
    python prepare_dataset.py --val-split 0.2
"""

import os
import sys
import shutil
import random
import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description='Prepare YOLO-OBB dataset')
    parser.add_argument('--val-split', type=float, default=0.2, 
                        help='Validation split ratio (default: 0.2 = 20%%)')
    parser.add_argument('--data-dir', default='../data', help='Source data directory')
    parser.add_argument('--seed', type=int, default=42, help='Random seed for reproducibility')
    args = parser.parse_args()
    
    random.seed(args.seed)
    
    # Resolve paths
    script_dir = Path(__file__).parent
    data_dir = Path(args.data_dir)
    if not data_dir.is_absolute():
        data_dir = script_dir / data_dir
    
    images_dir = data_dir / 'images'
    labels_dir = data_dir / 'labels'
    
    # Check source directories exist
    if not images_dir.exists() or not labels_dir.exists():
        print(f"Error: Source directories not found: {images_dir}, {labels_dir}")
        return 1
    
    # Get all image files
    image_files = list(images_dir.glob('*.jpg')) + list(images_dir.glob('*.png'))
    
    if not image_files:
        print(f"Error: No images found in {images_dir}")
        return 1
    
    print(f"Found {len(image_files)} images")
    
    # Filter to only include images that have corresponding labels
    valid_pairs = []
    missing_labels = 0
    
    for img_path in image_files:
        label_path = labels_dir / f"{img_path.stem}.txt"
        if label_path.exists():
            valid_pairs.append((img_path, label_path))
        else:
            missing_labels += 1
    
    if missing_labels > 0:
        print(f"Warning: {missing_labels} images missing labels (skipped)")
    
    print(f"Valid image-label pairs: {len(valid_pairs)}")
    
    if len(valid_pairs) < 10:
        print("Error: Need at least 10 image-label pairs")
        return 1
    
    # Shuffle and split
    random.shuffle(valid_pairs)
    val_count = int(len(valid_pairs) * args.val_split)
    train_count = len(valid_pairs) - val_count
    
    train_pairs = valid_pairs[:train_count]
    val_pairs = valid_pairs[train_count:]
    
    print(f"Split: {train_count} train, {val_count} val")
    
    # Create output directories
    train_images_dir = data_dir / 'train' / 'images'
    train_labels_dir = data_dir / 'train' / 'labels'
    val_images_dir = data_dir / 'val' / 'images'
    val_labels_dir = data_dir / 'val' / 'labels'
    
    for d in [train_images_dir, train_labels_dir, val_images_dir, val_labels_dir]:
        d.mkdir(parents=True, exist_ok=True)
    
    # Copy files
    print("Copying training files...")
    for img_path, label_path in train_pairs:
        shutil.copy2(img_path, train_images_dir / img_path.name)
        shutil.copy2(label_path, train_labels_dir / label_path.name)
    
    print("Copying validation files...")
    for img_path, label_path in val_pairs:
        shutil.copy2(img_path, val_images_dir / img_path.name)
        shutil.copy2(label_path, val_labels_dir / label_path.name)
    
    # Create dataset.yaml
    config_dir = script_dir.parent / 'config'
    config_dir.mkdir(parents=True, exist_ok=True)
    
    yaml_content = f"""# YOLO-OBB Dataset Configuration
# Auto-generated by prepare_dataset.py

path: {data_dir.absolute()}  # dataset root directory
train: train/images  # train images relative to path
val: val/images  # val images relative to path

# Classes
names:
  0: component

# Dataset info
# Total images: {len(valid_pairs)}
# Train: {train_count}
# Val: {val_count}
# Val split: {args.val_split * 100:.0f}%
"""
    
    yaml_path = config_dir / 'dataset.yaml'
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)
    
    print(f"\nDataset prepared successfully!")
    print(f"  Train: {train_images_dir}")
    print(f"  Val: {val_images_dir}")
    print(f"  Config: {yaml_path}")
    
    return 0


if __name__ == '__main__':
    sys.exit(main())

